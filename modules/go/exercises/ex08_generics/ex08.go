//
//   - (*Set[T]) Add(x T)
//     Добавляет значение. Повторное добавление существующего — без эффекта.
//
//   - (*Set[T]) Contains(x T) bool
//     Сообщает, есть ли значение в множестве.
//
//   - (*Set[T]) Len() int
//     Количество уникальных элементов.
//
