// Package ex12sync — упражнение по потокобезопасности и примитивам sync.
//
// # Задача
//
// Реализуй два потокобезопасных компонента. Главная сложность не в алгоритме, а в
// КОРРЕКТНОСТИ под конкурентной нагрузкой: тесты запускают сотни горутин и гоняются
// с детектором гонок (go test -race ./ex12_sync/). Любой незащищённый доступ к общему
// состоянию (одновременные чтение и запись map без синхронизации) будет обнаружен и
// провалит тест. Без -race тесты тоже должны быть зелёными.
//
// ## Часть 1. SafeCache[K, V] — потокобезопасный кэш на RWMutex
//
// Обобщённый кэш «ключ → значение», безопасный при доступе из множества горутин
// одновременно. Тип объявлен ниже как:
//
//	type SafeCache[K comparable, V any] struct { ... }
//
// Реализуй конструктор и методы:
//
//   - func NewSafeCache[K comparable, V any]() *SafeCache[K, V]
//     Создаёт готовый к работе пустой кэш.
//
//   - func (c *SafeCache[K, V]) Set(key K, value V)
//     Кладёт (или перезаписывает) значение по ключу.
//
//   - func (c *SafeCache[K, V]) Get(key K) (V, bool)
//     Возвращает значение и true, если ключ есть; иначе zero value и false
//     (та же comma-ok семантика, что у чтения из map).
//
//   - func (c *SafeCache[K, V]) Len() int
//     Текущее число элементов.
//
// Требования к контракту:
//   - Доступ к внутреннему состоянию из разных горутин ДОЛЖЕН быть синхронизирован
//     так, чтобы программа была корректна под -race.
//   - Операции чтения (Get, Len) и записи (Set) должны корректно работать при
//     одновременном вызове из многих горутин. Подумай, какой примитив позволяет
//     множеству читателей идти параллельно, но писателю — эксклюзивно.
//   - Нулевое значение типа НЕ обязано быть рабочим: пользоваться кэшем разрешено
//     только после конструктора NewSafeCache.
//
// ## Часть 2. Memoize — мемоизация с семантикой single-flight
//
// Реализуй функцию-обёртку:
//
//	func Memoize(fn func(int) int) func(int) int
//
// Она возвращает новую функцию того же вида, которая кэширует результаты fn по
// аргументу: повторный вызов с уже виденным аргументом возвращает сохранённый
// результат, не вызывая fn снова.
//
// Ключевое (и самое сложное) требование — КОРРЕКТНОСТЬ ПОД КОНКУРЕНЦИЕЙ при
// семантике single-flight: если МНОЖЕСТВО горутин одновременно зовут обёртку с
// ОДНИМ И ТЕМ ЖЕ ещё не вычисленным аргументом, базовая fn для этого аргумента
// должна выполниться РОВНО ОДИН РАЗ. Остальные обязаны дождаться того же результата,
// а не запустить свой параллельный расчёт. Разные аргументы вычисляются независимо
// и не должны блокировать друг друга без необходимости.
//
// Требования к контракту:
//   - На каждый аргумент fn вызывается не более одного раза за всё время жизни
//     обёртки, даже при конкурентных вызовах (это проверяется счётчиком вызовов
//     через atomic).
//   - Для одинакового аргумента все вызовы возвращают одно и то же значение.
//   - Обёртка потокобезопасна (корректна под -race).
//   - fn может быть «медленной»; пока она считает один аргумент, вызовы с ДРУГИМ,
//     уже готовым аргументом не должны висеть в ожидании.
//
// Подсказок по реализации в коде нет — пиши сам. Тема и нужные примитивы (RWMutex,
// Mutex, Once, atomic, happens-before) разобраны в theory/MEMORY_GC.md и
