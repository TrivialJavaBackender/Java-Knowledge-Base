// Package ex06channels — упражнение по горутинам, каналам и select.
//
// # Задача
//
// Реализуй три классических примитива конкурентности на каналах. Главная сложность
// не в алгоритме, а в КОРРЕКТНОМ управлении жизненным циклом каналов и горутин:
// выходной канал должен закрываться ровно один раз и ровно тогда, когда источники
// исчерпаны; ни одна горутина не должна навсегда зависнуть на send/receive.
//
// Тесты запускаются с -race и под таймаутом: гонка при записи в общий канал,
// забытый close (читатель повиснет на range) или зависший отправитель будут
// обнаружены автоматически.
//
// # Что нужно сделать
//
//  1. func Merge(chans ...<-chan int) <-chan int      // fan-in
//     Объединяет произвольное число входных каналов в один выходной. Значения из
//     всех источников попадают в выход (порядок между источниками не определён —
//     это нормально). Выходной канал ДОЛЖЕН быть закрыт после того, как закрылись
//     ВСЕ входные (и ни секундой раньше). При нуле источников — вернуть уже пустой
//     закрытый канал (range по нему завершается сразу).
//     Подсказка по смыслу (не по коду): на каждый источник — своя горутина-читатель;
//     отдельный механизм ждёт, пока все читатели закончат, и только потом закрывает
//     выход. Закрывать выход должна ровно одна сторона.
//
//  2. func Pipeline(in <-chan int) <-chan int
//     Двухстадийный конвейер. Стадия 1: возвести каждое значение в квадрат (x*x).
//     Стадия 2: пропустить значение как есть (тождественная стадия — её наличие
//     важно, чтобы ты связал ДВА канала между собой, а не сделал одну функцию).
//     Порядок значений сохраняется. Выход закрывается, когда закрыт вход; каждая
//     стадия закрывает СВОЙ выходной канал по завершении своего входа.
//
//  3. func FirstResponse(chans ...<-chan string) string
//     Возвращает первое значение, пришедшее из ЛЮБОГО источника, и сразу выходит,
//     не дожидаясь остальных. Реализуй через select по всем каналам одновременно
//     (а не последовательным receive — это блокировало бы на первом канале).
//     Гарантируется хотя бы один источник и хотя бы одно значение.
//
// # Правила
//
//   - close вызывает только сторона-отправитель и ровно один раз (повторный close
//     или send в закрытый канал паникует).
//   - receive из закрытого канала отдаёт zero value и ok=false — учитывай это, когда
//     решаешь, жив ли источник.
//   - Никаких time.Sleep для «синхронизации». Синхронизация — только каналами
//     (и, если нужно, sync.WaitGroup).
//
// Реализация должна жить только в этом файле. Тесты (ex06_test.go) менять не нужно.
