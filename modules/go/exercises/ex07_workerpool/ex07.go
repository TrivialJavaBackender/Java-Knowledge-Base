// Package ex07workerpool — упражнение по теме «Паттерны конкурентности»:
// пул воркеров с ограничением параллелизма и корректной отменой через context.
//
// # Задача
//
// Реализуй ProcessAll — обработку набора заданий пулом из фиксированного числа
// воркеров. Это классический worker pool: N горутин разбирают задания из общего
// канала и складывают результаты. Сложность — в корректной остановке: при ПЕРВОЙ
// ошибке любого задания ИЛИ при отмене переданного context обработка должна
// прекратиться, а функция — вернуть соответствующую ошибку. И в любом исходе
// (успех, ошибка, отмена) НИ ОДНА горутина не должна остаться висеть (никаких
// утечек горутин).
//
// # Сигнатура
//
//	func ProcessAll(
//	    ctx context.Context,
//	    jobs []Job,
//	    workers int,
//	    fn func(context.Context, Job) (Result, error),
//	) ([]Result, error)
//
// # Требования
//
//  1. Параллелизм ограничен: одновременно выполняется НЕ больше workers вызовов fn.
//     (workers > 0; для пустого jobs возвращай (пустой/nil срез, nil) не запуская
//     лишней работы.)
//
//  2. Каждое задание обрабатывается ровно один раз вызовом fn(ctx, job). Порядок
//     результатов в возвращаемом срезе НЕ важен — важно, что при полном успехе там
//     ровно по одному Result на каждое входное задание.
//
//  3. Отмена / дедлайн: если ctx отменяется (или истекает его таймаут), пул должен
//     перестать брать новые задания и завершиться. ProcessAll возвращает ошибку
//     контекста (ctx.Err(): context.Canceled или context.DeadlineExceeded).
//     Передавай ctx внутрь fn, чтобы долгие задания тоже могли прерваться.
//
//  4. Первая ошибка fail-fast: если какой-то вызов fn вернул ненулевую ошибку —
//     ProcessAll прекращает обработку остальных и возвращает ИМЕННО эту ошибку
//     (errors.Is(returned, thatErr) == true). Если ошибок несколько, достаточно
//     вернуть любую из возникших (как правило — первую).
//
//  5. Никаких утечек горутин: к моменту возврата из ProcessAll все запущенные
//     горутины должны завершиться. Не оставляй горутину заблокированной на отправке
//     в канал, который уже никто не читает.
//
//  6. Никаких гонок данных: сборка результатов и ошибки должна быть потокобезопасной.
//     Решение обязано проходить `go test -race`.
//
// # Ограничения
//
//   - Только стандартная библиотека (подойдут sync и context). НЕ используй
//     errgroup или другие сторонние пакеты — собери логику отмены и сбора ошибки
//     вручную.
//   - Реализация — только в этом файле. Файл ex07_test.go менять не нужно.
//
// # Подсказок по реализации в коде нет — см. theory/CONCURRENCY_PATTERNS.md.
