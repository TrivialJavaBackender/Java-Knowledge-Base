// # func Dedup(s []int) []int
//
// Возвращает новый слайс, в котором оставлены только ПЕРВЫЕ вхождения каждого
// значения, в исходном порядке. Дубликаты (повторные вхождения уже встреченного
// значения) выбрасываются.
//
//	Dedup([]int{1, 2, 1, 3, 2, 3})  ->  [1 2 3]
//	Dedup([]int{5, 5, 5})           ->  [5]
//	Dedup([]int{})                  ->  []   (пустой, НЕ nil)
//	Dedup(nil)                      ->  []   (пустой, НЕ nil)
//
// Требования:
//   - порядок сохраняется (порядок первых вхождений);
//   - входной слайс s НЕ должен быть изменён (ни длина, ни элементы, ни его
//     backing-массив) — работай так, чтобы вызывающая сторона не пострадала;
//   - результат — всегда не-nil слайс (для пустого/nil входа верни пустой не-nil).
//
// # func GroupByParity(nums []int) map[string][]int
//
// Группирует числа по чётности в map с РОВНО двумя ключами: "even" и "odd".
// Внутри каждой группы порядок чисел — как во входном слайсе.
//
//	GroupByParity([]int{1, 2, 3, 4, 5})  ->  {"even": [2 4], "odd": [1 3 5]}
//	GroupByParity([]int{2, 4})           ->  {"even": [2 4], "odd": []}
//	GroupByParity(nil)                   ->  {"even": [],    "odd": []}
//
// Требования:
//   - в результате ВСЕГДА присутствуют оба ключа "even" и "odd", даже если
//     соответствующая группа пуста (значение — пустой не-nil слайс []int{});
//   - ноль (0) считается чётным; отрицательные: чётность по модулю 2
//     (т.е. -3 — нечётное, -4 — чётное);
//   - результирующий map не nil.
//
// # func RemoveAt[T any](s []T, i int) []T
//
// Удаляет элемент с индексом i, СОХРАНЯЯ порядок остальных, и возвращает
// получившийся слайс (длиной len(s)-1).
//
//	RemoveAt([]int{10, 20, 30, 40}, 1)  ->  [10 30 40]
//	RemoveAt([]string{"a", "b"}, 0)     ->  ["b"]
//
// Требования:
//   - индекс i вне диапазона [0, len(s)) → паника (это допустимо и ожидаемо;
//     достаточно естественной паники при выходе за границы);
//   - функция НЕ должна затирать элементы исходного backing-массива ЗА пределами
//     возвращаемого результата. Иначе говоря: если у вызывающей стороны есть
//     другой слайс, делящий тот же backing-массив и смотрящий на элементы правее,
//     он не должен «испортиться». (Подумай про cap и реаллокацию.)
//
// # func WordLengths(s string) map[string]int
//
// Разбивает строку на слова по пробельным разделителям и возвращает map
// «слово → длина слова В СИМВОЛАХ (рунах, не байтах)».
//
//	WordLengths("go is fun")        ->  {"go":2, "is":2, "fun":3}
//	WordLengths("  hello   world ") ->  {"hello":5, "world":5}
//	WordLengths("")                 ->  {}   (пустой не-nil map)
//	WordLengths("привет мир")       ->  {"привет":6, "мир":3}   ← по рунам, НЕ по байтам!
//	WordLengths("naïve café")       ->  {"naïve":5, "café":4}
//
// Требования:
//   - разделители — любые пробельные символы (пробелы, табы, переводы строк);
//     пустые слова (от повторных пробелов и пробелов по краям) игнорируются;
//   - длина считается в рунах: "привет" — это 6 символов, хотя 12 байтов;
//   - если одно и то же слово встречается дважды, его длина одна и та же —
//     просто перезапиши (значение детерминировано);
