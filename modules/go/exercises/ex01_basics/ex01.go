// 1. WordFrequency(text string) map[string]int
//
//	Возвращает частотный словарь слов: ключ — слово, значение — сколько раз оно
//	встретилось в text. Правила выделения слов:
//	  - Слово — это максимальная непрерывная последовательность символов, НЕ являющихся
//	    ASCII-пробельными. Пробельными считаются: ' ' (пробел), '\t', '\n', '\r'.
//	    Любой другой символ (буквы, цифры, пунктуация, не-ASCII руны) — часть слова.
//	  - Регистр игнорируется ТОЛЬКО для ASCII-букв 'A'..'Z' (приводятся к нижнему,
//	    прибавлением 32). Не-ASCII символы (например кириллица) оставляются как есть.
//	  - Подсчёт ведётся по словам, а не по символам.
//	Для пустой строки и строки только из пробелов возвращается пустой (НЕ nil)
//	словарь — так, чтобы len(result) == 0 и в него можно было записывать.
//	Примеры:
//	  WordFrequency("the cat the dog THE bird") => {"the":3, "cat":1, "dog":1, "bird":1}
//	  WordFrequency("a\tb\nc  a")               => {"a":2, "b":1, "c":1}
//	  WordFrequency("")                          => {} (непустой словарь нулевой длины)
//
// 2. MinMaxSum(nums []int) (min, max, sum int, err error)
//
//	За ОДИН проход по слайсу вычисляет минимум, максимум и сумму его элементов.
//	  - Если слайс пустой или nil — вернуть нулевые min/max/sum и НЕненулевую ошибку
//	    (текст на твоё усмотрение); в этом случае значения min/max/sum игнорируются
//	    вызывающим.
//	  - Для непустого слайса err == nil. Корректно работать с отрицательными числами
//	    и со слайсом из одного элемента (тогда min == max == этот элемент, sum == он же).
//	  - Нельзя использовать сортировку или несколько отдельных проходов «на каждую
//	    величину» — один цикл range.
//	Примеры:
//	  MinMaxSum([]int{3, 1, 4, 1, 5}) => min=1, max=5, sum=14, err=nil
//	  MinMaxSum([]int{-7})            => min=-7, max=-7, sum=-7, err=nil
//	  MinMaxSum(nil)                  => 0, 0, 0, err!=nil
//
// 3. ParseIntStrict(s string) (int, error)
//
//	Собственный СТРОГИЙ парсер десятичного целого БЕЗ strconv. Ручной разбор по
//	символам. Правила:
//	  - Допустим необязательный ведущий знак: '+' или '-'. Один знак, только в начале.
//	  - Далее — одна или более ASCII-цифр '0'..'9'. Никаких пробелов, букв, точек,
//	    разделителей разрядов, экспонент.
//	  - Пустая строка — ошибка. Строка только из знака ("+", "-") — ошибка.
//	  - Любой посторонний символ — ошибка (возврат 0 и ненулевой err).
//	  - Ведущие нули допустимы: "007" => 7, "-0" => 0, "+0" => 0.
//	  - Значение собирается арифметически (накопление acc = acc*10 + цифра); о
//	    переполнении int64-диапазона можно не заботиться — тесты не подают таких
//	    больших чисел. Знак применяется в конце.
//	При ошибке всегда возвращается (0, ненулевая ошибка). При успехе — (число, nil).
//	Примеры:
//	  ParseIntStrict("42")    => 42, nil
//	  ParseIntStrict("-123")  => -123, nil
//	  ParseIntStrict("+7")    => 7, nil
//	  ParseIntStrict("007")   => 7, nil
//	  ParseIntStrict("")      => 0, err
