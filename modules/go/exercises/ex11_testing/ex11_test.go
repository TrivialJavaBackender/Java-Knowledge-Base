// TestWordStats_Smoke — минимальный «дымовой» тест: один очевидный кейс.
// Его достаточно, чтобы пакет компилировался и `go test` был зелёным.
func TestWordStats_Smoke(t *testing.T) {
	got := WordStats("Go go GO")
	if got.Total != 3 {
		t.Errorf("Total = %d, want 3", got.Total)
	}
	if got.Unique != 1 {
		t.Errorf("Unique = %d, want 1", got.Unique)
	}
	if got.MostCommon != "go" {
		t.Errorf("MostCommon = %q, want %q", got.MostCommon, "go")
	}
}

