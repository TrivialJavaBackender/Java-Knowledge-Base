/**
 * Размер минимальной сессии и оценка времени — одни на приложение: их читают
 * дашборд, страница /review и текст push-уведомления. Расхождение было бы
 * заметно сразу: в нотификации «~5 минут», на экране «~7».
 *
 * Это чистый модуль без Prisma и без React — его тянут и серверные роуты, и
 * тесты (`lib/reminders.test.ts`), поэтому импорт базы сюда добавлять нельзя.
 */

/**
 * Сколько карточек в минимальной сессии. Смысл числа — психологический, а не
 * алгоритмический: очередь из 43 карточек читается как обязательство на
 * полчаса, «начнём с 5» — как две минуты. Расписание Лейтнера
 * (`lib/leitner.ts`) от этого не меняется вообще: каждая отвеченная карточка
 * проходит через тот же `reviewCard()`.
 */
export const MIN_SESSION_SIZE = 5;

/**
 * Секунд на карточку для оценки «~N минут». 20 с — это «прочитал вопрос,
 * вспомнил, раскрыл, отметил» без разбора теории.
 */
export const SECONDS_PER_CARD = 20;

/** «17 карточек» → 6 (минут). Ноль карточек — ноль минут, иначе минимум 1. */
export function estimateMinutes(cards: number): number {
  if (cards <= 0) return 0;
  return Math.max(1, Math.round((cards * SECONDS_PER_CARD) / 60));
}
